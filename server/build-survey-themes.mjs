// Regenerates survey-themes.mjs from the published Survey Feedback data in
// design-prototypes (app-analytics/survey-feedback/data/survey-feedback-data.js).
// Usage: node build-survey-themes.mjs <path-to-survey-feedback-data.js>
// Only theme names and counts are kept: no comment text.
import fs from "node:fs";
import vm from "node:vm";
const src = process.argv[2];
if (!src) { console.error("usage: node build-survey-themes.mjs <survey-feedback-data.js>"); process.exit(1); }
const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(src, "utf8"), sandbox);
const d = sandbox.window.PAYMENT_PLAN_PUBLISHED;
const themes = Object.fromEntries(d.themes.map(t => [t.id, { id: t.id, name: t.name, comments: 0, feature_request: 0, technical_bug: 0, high_risk: 0 }]));
for (const r of d.theme_counts) if (themes[r.theme_id]) themes[r.theme_id].comments += r.count;
for (const r of d.issue_signals) if (r.topic_level === "theme" && themes[r.topic_id] && r.signal in themes[r.topic_id]) themes[r.topic_id][r.signal] += r.count;
const all = { comments: 0, feature_request: 0, technical_bug: 0, high_risk: 0 };
for (const r of d.issue_signals) if (r.topic_level === "all" && r.signal in all) all[r.signal] += r.count;
all.comments = Object.values(themes).reduce((n, t) => n + t.comments, 0);
const out = { source: "design-prototypes/app-analytics/survey-feedback", dataset: d.metadata.dataset_name, build: d.metadata.build_version,
  period: [d.metadata.period_start, d.metadata.period_end], all, themes: Object.values(themes).sort((a, b) => b.comments - a.comments) };
fs.writeFileSync(new URL("./survey-themes.mjs", import.meta.url), "// Generated by build-survey-themes.mjs. Do not edit.\nexport default " + JSON.stringify(out, null, 2) + ";\n");
console.log(`wrote survey-themes.mjs: ${out.themes.length} themes, ${all.comments} comments`);
