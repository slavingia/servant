// Regenerates survey-themes.mjs (the themes usage-topics.mjs labels token use
// with) from your own survey-feedback export. Only theme names, counts and match
// patterns are kept: no comment text.
//
//   node build-survey-themes.mjs <survey-feedback-data.(json|js)> [--themes-config themes.json] [--source "org/repo/path"]
//
// The data file is JSON, or a script that assigns one object to a window
// property (window.SURVEY_DATA = {...}). Its shape:
//   { metadata: { dataset_name, build_version, period_start, period_end },
//     themes: [{ id, name, match? }],
//     theme_counts: [{ theme_id, count }],
//     issue_signals: [{ topic_level: "theme" | "all", topic_id, signal: "feature_request" | "technical_bug" | "high_risk", count }] }
// The optional themes config adds or overrides the matching rules:
//   { "source": "org/repo/path", "context": "<regex>", "fallback": "<theme id>",
//     "themes": [{ "id": "<theme id>", "match": "<regex>" }] }
// Regexes are source strings, matched case-insensitively. A request counts as
// product work only if it matches `context`; the first theme whose `match` hits
// wins (themes are tried in config order, then data order), else `fallback`.
// Everything else is "other". The committed survey-themes.mjs is a synthetic example.
import fs from "node:fs";
import vm from "node:vm";

const args = process.argv.slice(2);
const flag = (name) => { const i = args.indexOf(`--${name}`); if (i < 0) return undefined; const v = args[i + 1]; args.splice(i, 2); return v; };
const configPath = flag("themes-config");
const sourceArg = flag("source");
const src = args[0];
if (!src) { console.error("usage: node build-survey-themes.mjs <survey-feedback-data.(json|js)> [--themes-config themes.json] [--source org/repo/path]"); process.exit(1); }

function readData(file) {
  const text = fs.readFileSync(file, "utf8");
  if (file.endsWith(".json")) return JSON.parse(text);
  const sandbox = { window: {} };
  vm.runInNewContext(text, sandbox);
  const values = Object.values(sandbox.window);
  if (values.length !== 1) throw new Error("the data script must assign exactly one window property");
  return values[0];
}
const d = readData(src);
const cfg = configPath ? JSON.parse(fs.readFileSync(configPath, "utf8")) : {};
const checkRegex = (what, source) => {
  if (typeof source !== "string" || !source) throw new Error(`${what}: a regex source string is required`);
  new RegExp(source, "i"); // throws on a bad pattern
  return source;
};

const themes = new Map(d.themes.map(t => [t.id, { id: t.id, name: t.name, comments: 0, feature_request: 0, technical_bug: 0, high_risk: 0, ...(t.match ? { match: t.match } : {}) }]));
for (const r of d.theme_counts || []) if (themes.has(r.theme_id)) themes.get(r.theme_id).comments += r.count;
for (const r of d.issue_signals || []) if (r.topic_level === "theme" && themes.has(r.topic_id) && r.signal in themes.get(r.topic_id)) themes.get(r.topic_id)[r.signal] += r.count;
const all = { comments: 0, feature_request: 0, technical_bug: 0, high_risk: 0 };
for (const r of d.issue_signals || []) if (r.topic_level === "all" && r.signal in all) all[r.signal] += r.count;
all.comments = [...themes.values()].reduce((n, t) => n + t.comments, 0);

// Match order: themes named in the config first (in its order), then the rest in data order.
const configured = Array.isArray(cfg.themes) ? cfg.themes : [];
for (const t of configured) {
  if (!themes.has(t.id)) throw new Error(`themes config names ${t.id}, which is not in the data`);
  themes.get(t.id).match = t.match;
}
const order = [...configured.map(t => t.id), ...[...themes.keys()].filter(id => !configured.some(t => t.id === id))];
const ordered = order.map(id => themes.get(id));
for (const t of ordered) if (t.match !== undefined) checkRegex(`theme ${t.id}`, t.match);
const context = checkRegex("context", cfg.context ?? d.context);
const fallback = cfg.fallback ?? d.fallback ?? null;
if (fallback !== null && !themes.has(fallback)) throw new Error(`fallback ${fallback} is not a theme`);

const out = {
  source: sourceArg || cfg.source || d.metadata?.source || "",
  dataset: d.metadata.dataset_name, build: d.metadata.build_version,
  period: [d.metadata.period_start, d.metadata.period_end],
  all, context, fallback, themes: ordered,
};
fs.writeFileSync(new URL("./survey-themes.mjs", import.meta.url), "// Generated by build-survey-themes.mjs. Do not edit.\nexport default " + JSON.stringify(out, null, 2) + ";\n");
console.log(`wrote survey-themes.mjs: ${out.themes.length} themes, ${all.comments} comments`);
